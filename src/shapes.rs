pub fn get_cube(x: f32, y: f32, z: f32) -> [[[f32; 3]; 2]; 12] {
    let z = 2.0;
    let edges = [
        [[-0.5 + x, -0.5 + y, z - 0.5], [0.5 + x, -0.5 + y, z - 0.5]],
        [[-0.5 + x, 0.5 + y, z - 0.5], [0.5 + x, 0.5 + y, z - 0.5]],
        [[-0.5 + x, -0.5 + y, z - 0.5], [-0.5 + x, 0.5 + y, z - 0.5]],
        [[0.5 + x, -0.5 + y, z - 0.5], [0.5 + x, 0.5 + y, z - 0.5]],
        [[-0.5 + x, -0.5 + y, z + 0.5], [0.5 + x, -0.5 + y, z + 0.5]],
        [[-0.5 + x, 0.5 + y, z + 0.5], [0.5 + x, 0.5 + y, z + 0.5]],
        [[-0.5 + x, -0.5 + y, z + 0.5], [-0.5 + x, 0.5 + y, z + 0.5]],
        [[0.5 + x, -0.5 + y, z + 0.5], [0.5 + x, 0.5 + y, z + 0.5]],
        [[-0.5 + x, -0.5 + y, z - 0.5], [-0.5 + x, -0.5 + y, z + 0.5]],
        [[0.5 + x, -0.5 + y, z - 0.5], [0.5 + x, -0.5 + y, z + 0.5]],
        [[-0.5 + x, 0.5 + y, z - 0.5], [-0.5 + x, 0.5 + y, z + 0.5]],
        [[0.5 + x, 0.5 + y, z - 0.5], [0.5 + x, 0.5 + y, z + 0.5]],
    ];
    return edges;
}

pub fn get_pyramid(x: f32, y: f32, z: f32) -> [[[f32; 3]; 2]; 6] {
    let z = 2.0;
    let edges = [
        [[0.0 + x, 0.5 + y, z - 0.5], [0.0 + x, -0.5 + y, z]],
        [[-0.5 + x, 0.5 + y, z + 0.5], [0.0 + x, -0.5 + y, z]],
        [[0.5 + x, 0.5 + y, z + 0.5], [0.0 + x, -0.5 + y, z]],
        [[0.0 + x, 0.5 + y, z - 0.5], [-0.5 + x, 0.5 + y, z + 0.5]],
        [[0.0 + x, 0.5 + y, z - 0.5], [0.5 + x, 0.5 + y, z + 0.5]],
        [[0.5 + x, 0.5 + y, z + 0.5], [-0.5 + x, 0.5 + y, z + 0.5]],
    ];
    return edges;
}
