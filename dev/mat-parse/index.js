const fs = require("fs");

function readCMPFile() {
  const compare = false;
  const range = [64, 832];
  const paths = [
    __dirname + "/dflt.cmp", 
    // __dirname + "/16red.cmp", 
    // __dirname + "/09fuel.cmp", 
    // __dirname + "/01yellow.cmp"
  ];
  const narr = [];
  for (let i = 0; i < paths.length; i++) {
    const path = paths[i];
    const data = fs.readFileSync(path);
    const buffer = new Uint8Array(data);
    for (let j = range[0]; j < range[1] && j < buffer.length; j++) {
      const byte = buffer[j];
      if (compare) {
        if (narr.length > j) {
          narr[j] += " - " + byte;
        } else {
          narr.push(j + " : " + byte);
        }
      } else {
        narr.push(byte);
      }
    }
  }
  if (compare) {
    console.log(narr); 
  } else {
    console.log(narr.join(", ")); 
  }
}

